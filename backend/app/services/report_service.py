from typing import List, Optional
from sqlalchemy.orm import Session
from sqlalchemy import func
from app.models.models import SecurityEvent, Alert, Incident, DetectionRule
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable

def generate_events_csv(events: List[SecurityEvent]) -> str:
    """Generates CSV string of security events."""
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "Event ID", "Timestamp (UTC)", "Source Type", "Source System",
        "Username", "Source IP", "Event Type", "Action", "Resource",
        "Status", "Severity", "Detection Status"
    ])
    for e in events:
        writer.writerow([
            e.id,
            e.event_timestamp.strftime("%Y-%m-%d %H:%M:%S") if e.event_timestamp else "",
            e.source_type,
            e.source_name,
            e.username or "",
            e.source_ip or "",
            e.event_type,
            e.action or "",
            e.resource or "",
            e.status,
            e.severity,
            e.detection_status
        ])
    return output.getvalue()

def generate_incidents_csv(incidents: List[Incident]) -> str:
    """Generates CSV string of incidents."""
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "Incident ID", "Title", "Severity", "Status",
        "Assigned Analyst", "Created At (UTC)", "Resolved At (UTC)", "Resolution Summary"
    ])
    for inc in incidents:
        writer.writerow([
            inc.id,
            inc.title,
            inc.severity,
            inc.status,
            inc.assigned_user.name if inc.assigned_user else "Unassigned",
            inc.created_at.strftime("%Y-%m-%d %H:%M:%S") if inc.created_at else "",
            inc.resolved_at.strftime("%Y-%m-%d %H:%M:%S") if inc.resolved_at else "",
            inc.resolution_summary or ""
        ])
    return output.getvalue()

def generate_security_pdf_report(db: Session, title: str = "CloudSentinel Security Executive Summary") -> bytes:
    """Generates a professional PDF report using ReportLab."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#0F172A'),
        spaceAfter=6
    )
    subtitle_style = ParagraphStyle(
        'DocSub',
        parent=styles['Normal'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#64748B'),
        spaceAfter=14
    )
    h2_style = ParagraphStyle(
        'Heading2',
        parent=styles['Heading2'],
        fontSize=13,
        leading=17,
        textColor=colors.HexColor('#1E293B'),
        spaceBefore=12,
        spaceAfter=6
    )
    normal_style = ParagraphStyle(
        'NormalText',
        parent=styles['Normal'],
        fontSize=9,
        leading=13,
        textColor=colors.HexColor('#334155')
    )

    elements = []

    # Title & Metadata
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    elements.append(Paragraph(title, title_style))
    elements.append(Paragraph(f"Generated by CloudSentinel Security Information & Event Management (SIEM) | {now_str}", subtitle_style))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#3B82F6'), spaceAfter=14))

    # Metrics Summary
    total_events = db.query(SecurityEvent).count()
    crit_alerts = db.query(Alert).filter(Alert.severity == "critical").count()
    high_alerts = db.query(Alert).filter(Alert.severity == "high").count()
    med_alerts = db.query(Alert).filter(Alert.severity == "medium").count()
    open_incidents = db.query(Incident).filter(Incident.status.in_(["open", "investigating"])).count()
    failed_logins = db.query(SecurityEvent).filter(
        SecurityEvent.event_type.in_(["login", "login_attempt"]),
        SecurityEvent.status.in_(["failed", "denied"])
    ).count()

    elements.append(Paragraph("1. Executive Threat Metrics Overview", h2_style))
    summary_data = [
        ["Total Processed Logs", "Critical Alerts", "High Alerts", "Failed Logins", "Active Incidents"],
        [str(total_events), str(crit_alerts), str(high_alerts), str(failed_logins), str(open_incidents)]
    ]
    summary_table = Table(summary_data, colWidths=[108, 108, 108, 108, 108])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1E293B')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 9),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BACKGROUND', (0, 1), (-1, 1), colors.HexColor('#F1F5F9')),
        ('FONTNAME', (0, 1), (-1, 1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 1), (-1, 1), 12),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
    ]))
    elements.append(summary_table)
    elements.append(Spacer(1, 14))

    # Top Recent Security Alerts
    elements.append(Paragraph("2. Top Recent Threat Alerts", h2_style))
    recent_alerts = db.query(Alert).order_by(Alert.created_at.desc()).limit(8).all()
    if recent_alerts:
        alert_rows = [["Title", "Severity", "Status", "Occurrences", "Target User / IP"]]
        for a in recent_alerts:
            user_ip = f"{a.affected_user or '-'} / {a.affected_ip or '-'}"
            alert_rows.append([
                Paragraph(a.title[:45], normal_style),
                a.severity.upper(),
                a.status.upper(),
                str(a.occurrence_count),
                Paragraph(user_ip[:30], normal_style)
            ])
        alert_table = Table(alert_rows, colWidths=[180, 75, 75, 65, 145])
        alert_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0F172A')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 8),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(alert_table)
    else:
        elements.append(Paragraph("No security alerts currently recorded.", normal_style))

    elements.append(Spacer(1, 14))

    # Incidents Status
    elements.append(Paragraph("3. Security Incidents Status", h2_style))
    recent_incidents = db.query(Incident).order_by(Incident.created_at.desc()).limit(6).all()
    if recent_incidents:
        inc_rows = [["Incident ID", "Title", "Severity", "Status", "Created"]]
        for inc in recent_incidents:
            inc_rows.append([
                inc.id[:8] + "...",
                Paragraph(inc.title[:40], normal_style),
                inc.severity.upper(),
                inc.status.upper(),
                inc.created_at.strftime("%Y-%m-%d %H:%M")
            ])
        inc_table = Table(inc_rows, colWidths=[70, 230, 75, 80, 85])
        inc_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0F172A')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 8),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(inc_table)
    else:
        elements.append(Paragraph("No active security incidents.", normal_style))

    elements.append(Spacer(1, 18))
    elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#CBD5E1'), spaceAfter=8))
    elements.append(Paragraph("CloudSentinel Security Log Monitoring Platform - Confidential Incident Report", subtitle_style))

    doc.build(elements)
    return buffer.getvalue()
