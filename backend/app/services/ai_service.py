import re
from typing import Optional, List, Dict, Any
from sqlalchemy.orm import Session
from app.models.models import Incident, Alert, SecurityEvent

def sanitize_untrusted_log(text: str) -> str:
    """Sanitizes raw log content to prevent prompt injection and credential leaks."""
    if not text:
        return ""
    # Mask potential passwords or tokens
    text = re.sub(r'(?i)(password|secret|token|api_key|access_key)["\']?\s*[:=]\s*["\']?([^"\'\s]+)', r'\1=***REDACTED***', text)
    # Neutralize prompt injection phrases
    suspicious_phrases = [
        "ignore previous instructions",
        "system prompt",
        "you are now an unfiltered ai",
        "override safety rules"
    ]
    cleaned = text
    for phrase in suspicious_phrases:
        cleaned = re.sub(phrase, "[FILTERED_SUSPICIOUS_PAYLOAD]", cleaned, flags=re.IGNORECASE)
    return cleaned[:1500]

def analyze_security_context(
    db: Session,
    query_type: str,
    target_id: Optional[str] = None,
    custom_prompt: Optional[str] = None
) -> Dict[str, Any]:
    """
    Produces structured, explainable security analysis, MITRE ATT&CK correlation,
    and investigation guidance adhering to cybersecurity best practices.
    """
    # 1. Incident Analysis
    if query_type == "incident_summary" and target_id:
        incident = db.query(Incident).filter(Incident.id == target_id).first()
        if incident:
            alerts_count = len(incident.alerts)
            alert_titles = [a.title for a in incident.alerts]
            affected_ips = list(set([a.affected_ip for a in incident.alerts if a.affected_ip]))
            affected_users = list(set([a.affected_user for a in incident.alerts if a.affected_user]))

            # Map to MITRE technique
            mitre_map = {
                "critical": "T1078 (Valid Accounts) / T1562 (Impair Defenses)",
                "high": "T1110 (Brute Force) / T1098 (Account Manipulation)",
                "medium": "T1087 (Account Discovery) / T1530 (Data from Cloud Storage)",
                "low": "T1059 (Command & Scripting Interpreter)"
            }
            mitre = mitre_map.get(incident.severity.lower(), "T1078 (Valid Accounts)")

            return {
                "analysis_title": f"Security Incident Assessment: {incident.title}",
                "summary": f"Incident '{incident.title}' currently in '{incident.status}' state correlates {alerts_count} active security alert(s). "
                           f"Primary actors observed: {', '.join(affected_users) or 'Unspecified'} across IP source(s) {', '.join(affected_ips) or 'Internal/Unknown'}.",
                "technical_breakdown": [
                    f"Severity Classification: {incident.severity.upper()} based on rule triggers and target resource sensitivity.",
                    f"Correlated Alerts: {', '.join(alert_titles) if alert_titles else 'Manually instantiated incident.'}",
                    f"Potential Impact: Unauthorized lateral movement, cloud audit blindspots, or credential misuse."
                ],
                "mitre_attack_technique": mitre,
                "risk_level": incident.severity.upper(),
                "recommended_actions": [
                    "Isolate or apply strict conditional access to the identified user account(s).",
                    "Verify if source IP addresses are associated with corporate egress or known threat proxies.",
                    "Review CloudTrail or identity provider audit records 60 minutes before and after the event.",
                    "Document containment steps and record findings in the Incident Timeline."
                ],
                "disclaimer": "AI recommendations are advisory. Analysts must independently verify telemetry before containment."
            }

    # 2. Alert Analysis
    if query_type == "alert_analysis" and target_id:
        alert = db.query(Alert).filter(Alert.id == target_id).first()
        if alert:
            return {
                "analysis_title": f"Threat Detection Breakdown: {alert.title}",
                "summary": f"This alert was generated by the CloudSentinel detection rule '{alert.rule.name if alert.rule else 'Rule Engine'}'. "
                           f"Observed {alert.occurrence_count} event recurrence(s). Target: {alert.affected_user or 'Global'} / Source IP: {alert.affected_ip or 'N/A'}.",
                "technical_breakdown": [
                    f"Rule Logic: Evaluated log activity against deterministic thresholds.",
                    f"First Seen: {alert.first_seen.strftime('%Y-%m-%d %H:%M:%S UTC')}, Last Recurrence: {alert.last_seen.strftime('%Y-%m-%d %H:%M:%S UTC')}.",
                    f"Linked Events: {len(alert.events)} raw security records attached."
                ],
                "mitre_attack_technique": "T1110.001 (Password Guessing) / T1078 (Cloud Accounts)",
                "risk_level": alert.severity.upper(),
                "recommended_actions": [
                    alert.recommended_action or "Review triggering security events in the Event Explorer.",
                    "Determine if user session was terminated or if subsequent successful access occurred.",
                    "Acknowledge the alert or elevate to a formal Incident if anomalous behavior continues."
                ],
                "disclaimer": "Rule evaluation output. Verify logs against user baseline activity."
            }

    # 3. Security Event Explanation / Log Translator
    if query_type in ["event_explanation", "log_translator"] and target_id:
        event = db.query(SecurityEvent).filter(SecurityEvent.id == target_id).first()
        if event:
            clean_log = sanitize_untrusted_log(event.raw_log or "")
            return {
                "analysis_title": f"Event Telemetry Breakdown: {event.event_type} ({event.source_name})",
                "summary": f"At {event.event_timestamp.strftime('%Y-%m-%d %H:%M:%S UTC')}, actor '{event.username or 'Anonymous'}' executed '{event.action or event.event_type}' "
                           f"on target resource '{event.resource or 'Infrastructure'}' resulting in '{event.status.upper()}'.",
                "technical_breakdown": [
                    f"Telemetry Source: {event.source_type} ({event.source_name}).",
                    f"Source IP Address: {event.source_ip or 'Not logged / Internal'}.",
                    f"Normalized Severity: {event.severity.upper()} | Detection Status: {event.detection_status.upper()}.",
                    f"Sanitized Raw Detail: {clean_log}"
                ],
                "mitre_attack_technique": "T1059 / T1078 (Authentication & Access)",
                "risk_level": event.severity.upper(),
                "recommended_actions": [
                    "Compare event timestamp with known scheduled jobs or deployment windows.",
                    "Search for other events sharing the same Source IP in the Event Explorer.",
                    "Verify if multi-factor authentication (MFA) was prompted and satisfied."
                ],
                "disclaimer": "Automated explanation provided for SOC tier-1 triage."
            }

    # Default / General Query Response
    return {
        "analysis_title": "CloudSentinel AI Security Assistant",
        "summary": "CloudSentinel Security Assistant processes cloud audit, authentication, and system events to detect lateral movement, credential abuse, and infrastructure tampering.",
        "technical_breakdown": [
            "Deterministic Rule Evaluation: Active",
            "Supported Standards: MITRE ATT&CK Cloud Matrix, CIS Benchmarks, NIST CSF",
            "Untrusted Log Sanitization: Enforced"
        ],
        "mitre_attack_technique": "Matrix for Enterprise & Cloud (AWS, Azure, GCP)",
        "risk_level": "INFORMATIONAL",
        "recommended_actions": [
            "Select any Alert or Incident to generate an automated investigation runbook.",
            "Inspect high-severity findings in the Security Alerts view.",
            "Export audit-ready compliance reports in the Reports module."
        ],
        "disclaimer": "Advisory telemetry synthesis. Human SOC analyst decision is required."
    }
